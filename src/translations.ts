// AI Translation logic
export const translateWithAI = async (text: string, targetLanguage: Language, apiKey: string): Promise<string> => {
  if (!apiKey || targetLanguage === 'English') return text;

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });
    
    const prompt = `Translate the following UI text to ${targetLanguage}. 
    Provide ONLY the translated text, no explanation or formatting.
    Text: "${text}"`;
    
    const result = await model.generateContent(prompt);
    return result.response.text().trim();
  } catch (error) {
    console.error("AI Translation failed:", error);
    return text;
  }
};

export const getStoredDynamicTranslations = (): Record<string, Record<string, string>> => {
  try {
    const saved = localStorage.getItem('aashalink_dynamic_translations');
    return saved ? JSON.parse(saved) : {};
  } catch (e) {
    return {};
  }
};

export const saveDynamicTranslation = (key: string, language: Language, translation: string) => {
  const current = getStoredDynamicTranslations();
  if (!current[key]) current[key] = {};
  current[key][language] = translation;
  localStorage.setItem('aashalink_dynamic_translations', JSON.stringify(current));
};
